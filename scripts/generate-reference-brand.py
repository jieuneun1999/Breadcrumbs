"""Transcribe the owner's reference into fixed ASCII/color rows for the Java CLI.

Optional artwork maintenance only: Pillow reads the supplied screenshot. The
generated Java data requires no image file, font, Python or Pillow at runtime.
Only the approved logo region is sampled; browser chrome and sample status/menu
data are excluded. Usage: python scripts/generate-reference-brand.py <reference>
"""
import hashlib
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'src/breadcrumbs/cli/ReferenceBrandArt.java'
WIDTH, HEIGHT = 158, 22
# Coordinates belong to the owner's 1920x1050 reference, not arbitrary screenshots.
LEFT, TOP, RIGHT, BOTTOM = 445, 195, 1480, 464
DENSITY = " .,:;+=*#%@"
PALETTE = [0x000000, 0x62411f, 0x815323, 0x9b6227, 0xb2732c, 0xc58631,
           0xd89a3c, 0xe8af50, 0xf3c06c, 0xffcf83, 0xffdc9e, 0xffe9bd]


def main():
    reference = Path(sys.argv[1])
    image = Image.open(reference).convert('RGB')
    if image.size != (1920, 1050):
        raise ValueError('Expected the approved 1920x1050 reference; revise the crop explicitly for another image.')
    marks, colors = [], []
    for row in range(HEIGHT):
        glyphs, bands = [], []
        y0 = TOP + (BOTTOM - TOP) * row // HEIGHT
        y1 = TOP + (BOTTOM - TOP) * (row + 1) // HEIGHT
        for column in range(WIDTH):
            x0 = LEFT + (RIGHT - LEFT) * column // WIDTH
            x1 = LEFT + (RIGHT - LEFT) * (column + 1) // WIDTH
            samples = []
            for y in range(y0, y1):
                for x in range(x0, x1):
                    # Replace the raster caption with real readable text in the renderer.
                    if (x >= 710 and 388 <= y <= 422) or (x >= 1080 and y < 265):
                        continue
                    red, green, blue = image.getpixel((x, y))
                    # Warm highlights/crust only. Dark backdrop/glow must not fill empty cells.
                    if red > 55 and red > green * 1.02 and green > blue * 1.08:
                        samples.append((red, green, blue))
            coverage = len(samples) / ((x1 - x0) * (y1 - y0))
            if coverage < 0.07:
                glyphs.append(' ')
                bands.append('0')
                continue
            rgb = tuple(sum(sample[c] for sample in samples) // len(samples) for c in range(3))
            palette_index = min(range(1, len(PALETTE)), key=lambda i: sum(
                (rgb[c] - ((PALETTE[i] >> (16 - c * 8)) & 255)) ** 2 for c in range(3)))
            # Ink covers only part of a terminal cell: lift lit surfaces while retaining dark depth.
            if palette_index >= 3:
                palette_index = min(len(PALETTE) - 1, palette_index + 2)
            # Coverage shapes the contour; foreground color carries the original lighting.
            density = min(len(DENSITY) - 1, max(1, round(coverage * (len(DENSITY) - 1))))
            glyphs.append(DENSITY[density])
            bands.append(format(palette_index, 'x'))
        marks.append(''.join(glyphs).rstrip())
        colors.append(''.join(bands).rstrip('0'))
    def java_rows(rows):
        return ',\n'.join('        "' + row.replace('\\', '\\\\').replace('"', '\\"') + '"' for row in rows)
    digest = hashlib.sha256(reference.read_bytes()).hexdigest()
    source = f'''package breadcrumbs.cli;

/**
 * Fixed terminal transcription of the owner's approved loaf/3D wordmark reference.
 * Generated by scripts/generate-reference-brand.py; only the logo region is used.
 * Each ASCII mark has a matching palette index. No image is loaded by the app.
 * Reference SHA-256: {digest}
 */
final class ReferenceBrandArt {{
    static final int WIDTH = {WIDTH};
    static final int[] PALETTE = {{{', '.join(f'0x{color:06x}' for color in PALETTE)}}};
    static final String[] MARKS = {{
{java_rows(marks)}
    }};
    static final String[] COLORS = {{
{java_rows(colors)}
    }};
    private ReferenceBrandArt() {{ }}
}}
'''
    DESTINATION.write_bytes(source.encode('utf-8'))
    print(f'Generated {WIDTH}x{HEIGHT} ASCII/color transcription; reference SHA-256 {digest}')


if __name__ == '__main__':
    main()
